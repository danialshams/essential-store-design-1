import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = p => readFileSync(p, "utf8");
test("new homepage includes four original editorial layouts and retains purchasing", () => {
  const home = read("src/components/AtelierHome.tsx");
  const tile = read("src/components/AtelierTile.tsx");
  const css = read("src/app/atelier-v2.css");
  assert.match(home, /atelier-hero/);
  assert.match(home, /atelier-sale-grid/);
  assert.match(home, /atelier-best-gallery/);
  assert.match(home, /atelier-new-gallery/);
  assert.match(home, /href="\/festival"/);
  assert.match(home, /festivalProducts\(store\)/);
  assert.match(tile, /toggleFavorite/);
  assert.match(tile, /add\(product\)/);
  assert.doesNotMatch(home, /ProductCard/);
  assert.match(css, /\.atelier-tile\{[^}]*background:transparent/);
  assert.match(css, /\.atelier-hero-image\{object-fit:contain/);
  assert.match(css, /\.site-footer\{margin-top:0!important/);
});
test("Grabfold WebGL loader reveals letters in RTL order and turns corner across screen", () => {
  const intro = read("src/components/AtelierIntro.tsx");
  const chrome = read("src/components/StoreChrome.tsx");
  const css = read("src/app/atelier-v2.css");
  assert.match(intro, /grabfold\/react/);
  assert.match(intro, /grabfold\/webgl/);
  assert.match(intro, /webglFold/);
  assert.match(intro, /binding="right"/);
  assert.match(intro, /pointerdown/);
  assert.match(intro, /pointermove/);
  assert.match(intro, /pointerup/);
  assert.match(intro, /TITLE\.length - 1 - index/);
  assert.match(intro, /previousOverflow\.current/);
  assert.match(chrome, /pathname==="\/"\?<AtelierIntro\/>/);
  assert.match(css, /z-index:999999/);
  assert.match(css, /prefers-reduced-motion/);
});
test("new photography is generated from bundled original editorial image sheets", () => {
  const src = read("scripts/prepare-atelier-media.mjs");
  const media = read("src/lib/showcase-photos.ts");
  const pkg = read("package.json");
  assert.match(src, /images\.unsplash\.com/);
  assert.match(src, /atelier-hero-desktop\.webp/);
  assert.match(src, /atelier-hero-mobile\.webp/);
  assert.match(src, /atelier-bag-b\.webp/);
  assert.match(media, /atelier-shoe-b\.webp/);
  assert.match(pkg, /prepare-atelier-media/);
});
